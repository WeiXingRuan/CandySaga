using System.Collections;
using System.Collections.Generic;
using UnityEngine;

public class CandyMove
{
    public int FromX;
    public int FromY;
    public int ToX;
    public int ToY;

    public CandyMove(int fromX, int fromY, int toX, int toY)
    {
        FromX = fromX;
        FromY = fromY;
        ToX = toX;
        ToY = toY;
    }
}
